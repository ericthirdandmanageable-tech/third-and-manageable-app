import { spawn } from "node:child_process";
import { writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const OUTPUT_URL = new URL("../src/lib/core/us-universities.ts", import.meta.url);
const DOWNLOADS_PAGE = "https://collegescorecard.ed.gov/data/";

const parseCsvRow = (line) => {
    const fields = [];
    let field = "";
    let quoted = false;

    for (let index = 0; index < line.length; index += 1) {
        const character = line[index];
        if (character === '"') {
            if (quoted && line[index + 1] === '"') {
                field += '"';
                index += 1;
            } else {
                quoted = !quoted;
            }
        } else if (character === "," && !quoted) {
            fields.push(field);
            field = "";
        } else {
            field += character;
        }
    }
    fields.push(field);
    return fields;
};

const downloadsResponse = await fetch(DOWNLOADS_PAGE);
if (!downloadsResponse.ok) {
    throw new Error(`College Scorecard downloads page failed (${downloadsResponse.status})`);
}

const downloadsHtml = await downloadsResponse.text();
const downloadPath = downloadsHtml.match(
    /href="([^"]*Most-Recent-Cohorts-Institution_[^"]+\.zip)"/,
)?.[1];
if (!downloadPath) throw new Error("Could not find the current institution download");

const downloadUrl = new URL(downloadPath, DOWNLOADS_PAGE);
const archiveResponse = await fetch(downloadUrl);
if (!archiveResponse.ok) {
    throw new Error(`College Scorecard download failed (${archiveResponse.status})`);
}

const temporaryDirectory = await mkdtemp(join(tmpdir(), "university-finder-"));
const archivePath = join(temporaryDirectory, "scorecard.zip");

try {
    await writeFile(archivePath, Buffer.from(await archiveResponse.arrayBuffer()));

    const unzip = spawn("unzip", [
        "-p",
        archivePath,
        "Most-Recent-Cohorts-Institution.csv",
    ]);
    const lines = createInterface({ input: unzip.stdout, crlfDelay: Infinity });
    let indexes;
    const institutions = [];

    for await (const line of lines) {
        const fields = parseCsvRow(line);
        if (!indexes) {
            const header = fields.map((field) => field.replace(/^\uFEFF/, ""));
            indexes = Object.fromEntries(
                ["UNITID", "INSTNM", "CITY", "STABBR", "MAIN", "HIGHDEG", "CURROPER"].map(
                    (column) => [column, header.indexOf(column)],
                ),
            );
            if (Object.values(indexes).some((index) => index < 0)) {
                throw new Error("College Scorecard CSV is missing a required column");
            }
            continue;
        }

        const highestDegree = Number(fields[indexes.HIGHDEG]);
        if (
            fields[indexes.CURROPER] !== "1" ||
            highestDegree < 2 ||
            highestDegree > 4
        ) {
            continue;
        }

        const institution = [
            Number(fields[indexes.UNITID]),
            fields[indexes.INSTNM],
            fields[indexes.CITY],
            fields[indexes.STABBR],
            Number(fields[indexes.MAIN]),
        ];
        if (institution.slice(0, 4).every(Boolean)) institutions.push(institution);
    }

    const exitCode = await new Promise((resolve, reject) => {
        unzip.once("error", reject);
        unzip.once("close", resolve);
    });
    if (exitCode !== 0) throw new Error(`unzip exited with status ${exitCode}`);

    institutions.sort(
        (left, right) =>
            left[1].localeCompare(right[1]) ||
            left[3].localeCompare(right[3]) ||
            left[2].localeCompare(right[2]),
    );

    const generatedAt = new Date().toISOString().slice(0, 10);
    const rows = institutions
        .map((institution) => `    ${JSON.stringify(institution)},`)
        .join("\n");
    const output = `// Generated by scripts/update-us-universities.mjs on ${generatedAt}.
// Source: U.S. Department of Education College Scorecard.
// Scope: operating institutions whose highest award is associate through graduate level.

export type UsUniversity = readonly [
    scorecardId: number,
    name: string,
    city: string,
    state: string,
    isMainCampus: 0 | 1,
];

export const US_UNIVERSITIES: readonly UsUniversity[] = [
${rows}
];
`;

    await writeFile(OUTPUT_URL, output);
    console.log(
        `Wrote ${institutions.length} institutions to ${fileURLToPath(OUTPUT_URL)}`,
    );
} finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
}
